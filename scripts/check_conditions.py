"""Fail the build when the SOTIF argument has a gap, in either direction.

    uv run --extra traceability python scripts/check_conditions.py

A triggering condition with no test is a claim nobody checked. A test claiming a
condition that does not exist is the quieter failure: it runs, it passes, and it
makes the taxonomy look complete while demonstrating nothing that was asserted.
One mistyped identifier is enough.

THE GATE ITSELF IS IMPORTED, NOT WRITTEN HERE. `fih.gate` came out of the fault
injection harness, where it was built against ISO 26262 requirements and then
attacked; the virtual production cell imports the same thing for its PackML
safety requirements. This is its third safety argument and the first one where
the requirements are perception insufficiencies rather than failures. That the
same gate fits all three is the point: the hazards differ, the evidence differs,
and the two ways an argument can have a hole do not.

The link is read by PARSING the test files rather than running them, so it
cannot be fooled by a marker inside a string and still works on a suite too
broken to collect, which is exactly when you want to know what is uncovered.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml
from fih.gate import (
    GateError,
    Requirement,
    as_evidence,
    check,
    check_chain,
    collect_marker_claims,
)

ROOT = Path(__file__).resolve().parents[1]
ANALYSIS = ROOT / "safety/triggering_conditions.yaml"
TESTS = ROOT / "tests"
REPORT = ROOT / "outputs/traceability.md"

#: The marker a test uses to claim a condition: @pytest.mark.demonstrates("TC-01")
MARKER = "demonstrates"


def load() -> dict:
    return yaml.safe_load(ANALYSIS.read_text(encoding="utf-8"))


def as_requirements(analysis: dict) -> tuple[Requirement, ...]:
    return tuple(
        Requirement(id=str(c["id"]), text=str(c["title"]), parent=str(c["hazard"]))
        for c in analysis["conditions"])


def matrix(analysis: dict, claimed: dict[str, list[tuple[str, str]]]) -> str:
    hazards = {str(h["id"]): h for h in analysis["hazards"]}
    lines = [
        "# Triggering condition to test traceability",
        "",
        "Generated by `scripts/check_conditions.py` from "
        "`safety/triggering_conditions.yaml` and the tests themselves. "
        "Do not edit by hand.",
        "",
        "Every condition traces up to a hazard and down to at least one test "
        "that recomputes its evidence from the committed results. The build "
        "fails on a gap in either direction.",
        "",
        "## Hazards", "",
        "| | Hazard | Harm |", "|---|---|---|",
    ]
    for hazard in analysis["hazards"]:
        lines.append(f"| {hazard['id']} | {hazard['text'].strip()} "
                     f"| {hazard['harm'].strip()} |")

    lines += ["", "## Triggering conditions, and what demonstrates them", "",
              "| | Condition | Hazard | Slices | Figures | Demonstrated by |",
              "|---|---|---|---|---|---|"]
    for condition in analysis["conditions"]:
        cid = str(condition["id"])
        tests = "<br>".join(f"`{test}`" for _, test in claimed.get(cid, []))
        # Evidence is a LIST of (slice, class, bin, ap) entries, one row per
        # measured figure, so that the test suite can enumerate every claim
        # rather than checking a subset somebody chose.
        slices = sorted({e["slice"] for e in condition["evidence"]})
        lines.append(f"| {cid} | {condition['title']} | {condition['hazard']} "
                     f"| {', '.join(slices)} | {len(condition['evidence'])} "
                     f"| {tests} |")

    negatives = analysis.get("negative_results", [])
    if negatives:
        lines += ["", "## Slices that showed nothing", "",
                  "Recorded because a taxonomy containing only the slices that "
                  "worked is a fishing expedition with the evidence removed.", ""]
        for item in negatives:
            lines.append(f"- **{item['slice']}**: {item['finding'].strip()}")

    lines += ["", "## Coverage", "",
              f"- Hazards: **{len(hazards)}**",
              f"- Triggering conditions: **{len(analysis['conditions'])}**",
              f"- Tests demonstrating a condition: "
              f"**{sum(len(v) for v in claimed.values())}**",
              f"- Measured figures, every one checked against the evaluation: "
              f"**{sum(len(c['evidence']) for c in analysis['conditions'])}**", ""]
    return "\n".join(lines)


def main() -> int:
    analysis = load()
    conditions = as_requirements(analysis)
    claimed = collect_marker_claims(TESTS, MARKER)

    try:
        check_chain(conditions, {str(h["id"]) for h in analysis["hazards"]},
                    child_kind="triggering condition", parent_kind="hazard")
        check(conditions, as_evidence(claimed))
    except GateError as gap:
        print("The SOTIF argument has a gap:\n")
        print(f"  {gap}")
        return 1

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(matrix(analysis, claimed), encoding="utf-8")
    print(f"traceability complete: {len(analysis['hazards'])} hazards, "
          f"{len(conditions)} triggering conditions, "
          f"{sum(len(v) for v in claimed.values())} demonstrating tests")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
